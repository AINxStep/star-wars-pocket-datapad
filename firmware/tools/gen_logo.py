#!/usr/bin/env python3
"""Rasterizes the Rebel crest SVG (single absolute M/C/L/Z path) into an
LVGL ALPHA_8BIT image header (include/rebel_logo.h). No dependencies.

Usage: python3 tools/gen_logo.py [svg] [size]
"""
import sys, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "..", "starwars-rebel-svgrepo-com.svg")
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 80
SS = 4  # supersampling factor per axis

from svgpath import load_polys
polys = load_polys(svg)

pts = [p for poly in polys for p in poly]
x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
scale = SIZE * SS / max(x1 - x0, y1 - y0)
ox = (SIZE * SS - (x1 - x0) * scale) / 2 - x0 * scale
oy = (SIZE * SS - (y1 - y0) * scale) / 2 - y0 * scale
edges = []
for poly in polys:
    q = [(x * scale + ox, y * scale + oy) for x, y in poly]
    for a, b in zip(q, q[1:] + q[:1]):
        if a[1] != b[1]: edges.append((a, b))

H = W = SIZE * SS
hi = [[0] * W for _ in range(H)]
for y in range(H):
    yc = y + 0.5
    xs = []
    for (ax, ay), (bx, by) in edges:
        if (ay <= yc < by) or (by <= yc < ay):
            xs.append((ax + (yc - ay) * (bx - ax) / (by - ay), 1 if by > ay else -1))
    xs.sort()
    wind = 0
    for k, (x, dirn) in enumerate(xs[:-1]):   # non-zero winding rule
        wind += dirn
        if wind != 0:
            for px in range(max(0, int(x + 0.5)), min(W, int(xs[k+1][0] + 0.5))):
                hi[y][px] = 1

alpha = []
for y in range(SIZE):
    for x in range(SIZE):
        s = sum(hi[y*SS + j][x*SS + k] for j in range(SS) for k in range(SS))
        alpha.append(round(255 * s / (SS * SS)))

out = os.path.join(root, "include", "rebel_logo.h")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_logo.py from starwars-rebel-svgrepo-com.svg - do not edit\n")
    f.write("#pragma once\n#include <lvgl.h>\n\n")
    f.write(f"static const uint8_t rebel_logo_map[] = {{\n")
    for r in range(0, len(alpha), 24):
        f.write("    " + ",".join(str(a) for a in alpha[r:r+24]) + ",\n")
    f.write("};\n\n")
    f.write("static const lv_img_dsc_t rebel_logo = {\n")
    f.write(f"    {{ LV_IMG_CF_ALPHA_8BIT, 0, 0, {SIZE}, {SIZE} }},\n")
    f.write(f"    {len(alpha)}, rebel_logo_map\n}};\n")
print(f"wrote {out} ({SIZE}x{SIZE}, {len(edges)} edges)")

# ASCII preview
for y in range(0, SIZE, 3):
    print("".join(" .:#"[min(3, alpha[y*SIZE+x] // 64)] for x in range(0, SIZE, 2)))
