#!/bin/sh
# Converts an Aurebesh font (TTF/OTF) into the LVGL fonts used by the firmware
# and enables them in include/aurebesh_font.h. Needs Node.js (lv_font_conv is
# fetched with npx).
#
# Sizes 12..28 mirror the Montserrat sizes of the UI (used when the interface
# language is Aurebesh; 18 and 24 serve the large-screen layouts) and fall back to Montserrat for symbols such as the
# arrows. Sizes 22 and 40 are used by the Aurebesh keyboard screen.
#
# Usage: tools/gen_aurebesh_font.sh path/to/Aurebesh.otf
set -e

FONT="$1"
if [ -z "$FONT" ] || [ ! -f "$FONT" ]; then
    echo "Usage: $0 path/to/Aurebesh.otf" >&2
    exit 1
fi

cd "$(dirname "$0")/.."

for SIZE in 12 14 16 18 20 24 28; do
    npx -y lv_font_conv --font "$FONT" -r 0x20-0x7E \
        --size $SIZE --bpp 4 --no-compress --format lvgl --lv-include lvgl.h \
        --lv-fallback lv_font_montserrat_$SIZE \
        --lv-font-name font_aurebesh_$SIZE -o src/ui/font_aurebesh_$SIZE.c
done
for SIZE in 22 40; do
    npx -y lv_font_conv --font "$FONT" -r 0x20-0x7E \
        --size $SIZE --bpp 4 --no-compress --format lvgl --lv-include lvgl.h \
        --lv-font-name font_aurebesh_$SIZE -o src/ui/font_aurebesh_$SIZE.c
done

# lv_font_conv records the full font path in a comment: keep only the file name
for F in src/ui/font_aurebesh_*.c; do
    sed -i.bak -E 's#--font [^ ]*/([^/ ]+\.(otf|ttf))#--font \1#' "$F" && rm -f "$F.bak"
done

cat > include/aurebesh_font.h <<'HDR'
#pragma once
#include <lvgl.h>

// Generated by tools/gen_aurebesh_font.sh
#define HAVE_AUREBESH_FONT 1
LV_FONT_DECLARE(font_aurebesh_12)
LV_FONT_DECLARE(font_aurebesh_14)
LV_FONT_DECLARE(font_aurebesh_16)
LV_FONT_DECLARE(font_aurebesh_18)
LV_FONT_DECLARE(font_aurebesh_20)
LV_FONT_DECLARE(font_aurebesh_22)
LV_FONT_DECLARE(font_aurebesh_24)
LV_FONT_DECLARE(font_aurebesh_28)
LV_FONT_DECLARE(font_aurebesh_40)
HDR

echo "Done. Rebuild and flash the firmware."
