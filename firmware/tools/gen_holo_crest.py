#!/usr/bin/env python3
"""Builds the outline of the Rebel crest used by the hologram module
(include/holo_crest.h) from the SVG: flattened, simplified (Ramer-Douglas-
Peucker) and normalized to [-1, 1] with +y up. No dependencies.

Usage: python3 tools/gen_holo_crest.py [svg] [epsilon]
"""
import math, os, sys
from svgpath import load_polys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "..", "starwars-rebel-svgrepo-com.svg")
EPS = float(sys.argv[2]) if len(sys.argv) > 2 else 0.25   # in SVG units (viewBox is 76 wide)


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    idx, dmax = 0, 0.0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            idx, dmax = i, d
    if dmax > eps:
        return rdp(pts[:idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [pts[0], pts[-1]]


polys = load_polys(svg)
allp = [p for poly in polys for p in poly]
cx = (min(p[0] for p in allp) + max(p[0] for p in allp)) / 2
cy = (min(p[1] for p in allp) + max(p[1] for p in allp)) / 2
half = max(max(p[0] for p in allp) - min(p[0] for p in allp),
           max(p[1] for p in allp) - min(p[1] for p in allp)) / 2

pts_out, ends = [], []
for poly in polys:
    # Closed polygon: split at the point farthest from the start so RDP has a real baseline
    far = max(range(len(poly)), key=lambda i: math.hypot(poly[i][0] - poly[0][0], poly[i][1] - poly[0][1]))
    simp = rdp(poly[:far + 1], EPS)[:-1] + rdp(poly[far:] + [poly[0]], EPS)[:-1]
    for x, y in simp:
        pts_out.append((round((x - cx) / half * 1000), round(-(y - cy) / half * 1000)))
    ends.append(len(pts_out))

out = os.path.join(root, "include", "holo_crest.h")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_holo_crest.py from starwars-rebel-svgrepo-com.svg - do not edit\n")
    f.write("#pragma once\n#include <stdint.h>\n\n")
    f.write("// Outline points scaled by 1000 (x right, y up, fits in [-1000, 1000])\n")
    f.write("static const int16_t HOLO_CREST_PTS[][2] = {\n")
    for i in range(0, len(pts_out), 6):
        f.write("    " + ", ".join(f"{{{x},{y}}}" for x, y in pts_out[i:i + 6]) + ",\n")
    f.write("};\n")
    f.write(f"static const int HOLO_CREST_POLYS = {len(ends)};\n")
    f.write("static const int HOLO_CREST_END[] = { " + ", ".join(map(str, ends)) + " };  // exclusive end index of each polygon\n")
print(f"{len(polys)} polygon(s), {len(pts_out)} points -> {out}")
