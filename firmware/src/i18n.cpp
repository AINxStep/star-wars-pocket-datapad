Lang lang_get(void) {
    uint8_t l = settings().language;
    return l < LANG_COUNT ? (Lang)l : LANG_ES;
}

const char* tr(StrId id) {
    if (id >= S_COUNT) return "";
    const Entry& e = table[id];
    switch (lang_get()) {
        case LANG_EN:  return e.en;
        case LANG_AUR: return e.aur ? e.aur : e.en;
        default:       return e.es;
    }
}
